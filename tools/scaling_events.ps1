# Used by build.ps1: init lines and generated JS of the NG+ / Scadutree Blessing choice events (grace
# submenu; flags in tools\EsdUtil\Bosses.cs; SpEffect rows from tools\gen_scaling.ps1): one NG+ event per
# boss (7980020), one Blessing event per DLC boss (7980021).
function Get-ScalingEvents($bosses, $root) {
    $scaling = (Get-Content (Join-Path $root 'src\scaling.json') -Raw -Encoding utf8 | ConvertFrom-Json).bosses
    $init = for ($i = 0; $i -lt $bosses.Count; $i++) {
        $b = $bosses[$i]; $f = $b.flags; $s = $scaling.($b.key)
        if (-not $s) { throw "src\scaling.json has no $($b.key): rerun tools\gen_scaling.ps1" }
        "    `$InitializeEvent($i, 7980020, $($f.active), $($f.warping), $($b.anchorEntity), $($b.bossEntity), $($s.g), $($s.invG));"
        if ($b.dlc) { "    `$InitializeEvent($i, 7980021, $($f.active), $($f.warping));" }
    }
    $ng = { param($t) 10000901 + $t }; $bl = { param($l) 10000911 + $l }
    $js = @(
        '// Generated by tools\scaling_events.ps1. NG+ choice (flags 10000900 custom, 10000901 + T): on arrival the'
        '// boss and its phase-one character get GameClear (world at NG, chosen NG+1..7) or its inverse (world at'
        '// NG+1.., chosen NG), the inverse of the world''s cycle factor and the chosen cycle''s (rows 7980200 + c /'
        '// 7980210 + t), then a full heal (SpEffect 110) for the new max HP; the last-phase character is healed again'
        '// when it starts fighting.'
        '$Event(7980020, Restart, function(activeFlag, warpingFlag, anchorEntity, bossEntity, gameClearSp, gameClearInverseSp) {'
        '    WaitFor(EventFlag(activeFlag) && !EventFlag(warpingFlag));'
        '    GotoIf(L9, !EventFlag(10000900));'
        '    WaitFixedTimeSeconds(1);'
        '    GotoIf(L1, Signed(gameClearSp) == 0);'
        "    if (GameCycle() == 0 && !EventFlag($(& $ng 0))) {"
        '        SetSpEffect(anchorEntity, gameClearSp);'
        '        SetSpEffect(bossEntity, gameClearSp);'
        '    }'
        "    if (GameCycle() >= 1 && EventFlag($(& $ng 0))) {"
        '        SetSpEffect(anchorEntity, gameClearInverseSp);'
        '        SetSpEffect(bossEntity, gameClearInverseSp);'
        '    }'
        'L1:'
        foreach ($c in 2..7) {
            $cond = if ($c -eq 7) { 'GameCycle() >= 7' } else { "GameCycle() == $c" }
            "    if ($cond) {"; "        SetSpEffect(anchorEntity, $(7980200 + $c));"; "        SetSpEffect(bossEntity, $(7980200 + $c));"; '    }'
        }
        foreach ($t in 2..7) {
            "    if (EventFlag($(& $ng $t))) {"; "        SetSpEffect(anchorEntity, $(7980210 + $t));"; "        SetSpEffect(bossEntity, $(7980210 + $t));"; '    }'
        }
        '    SetSpEffect(anchorEntity, 110);'
        '    SetSpEffect(bossEntity, 110);'
        '    GotoIf(L9, anchorEntity == bossEntity);'
        '    WaitFor(CharacterAIState(bossEntity, AIStateType.Combat) || !EventFlag(activeFlag));'
        '    GotoIf(L9, !EventFlag(activeFlag));'
        '    SetSpEffect(bossEntity, 110);'
        'L9:'
        '    WaitFor(!EventFlag(activeFlag));'
        '    RestartEvent();'
        '});'
        ''
        '// Generated by tools\scaling_events.ps1. Scadutree Blessing choice (flags 10000910 custom, 10000911 + L), DLC'
        '// bosses: on arrival the player gets the inverse of the level vanilla keeps on them (SpEffect 20000100 + L;'
        '// rows 7980530 + L) and the chosen level (rows 7980500 + L); removed when the reflection ends and on load.'
        '$Event(7980021, Restart, function(activeFlag, warpingFlag) {'
        foreach ($l in 0..20) { "    ClearSpEffect(10000, $(7980500 + $l));"; "    ClearSpEffect(10000, $(7980530 + $l));" }
        '    WaitFor(EventFlag(activeFlag) && !EventFlag(warpingFlag));'
        '    GotoIf(L9, !EventFlag(10000910));'
        '    WaitFixedTimeSeconds(2);'
        foreach ($l in 0..20) { "    if (CharacterHasSpEffect(10000, $(20000100 + $l))) {"; "        SetSpEffect(10000, $(7980530 + $l));"; '    }' }
        foreach ($l in 0..20) { "    if (EventFlag($(& $bl $l))) {"; "        SetSpEffect(10000, $(7980500 + $l));"; '    }' }
        'L9:'
        '    WaitFor(!EventFlag(activeFlag));'
        '    RestartEvent();'
        '});'
    )
    @{ init = @($init); js = ($js -join "`n") }
}
