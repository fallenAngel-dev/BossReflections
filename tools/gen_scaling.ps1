# Generates the SpEffect rows for the reflection's NG+ and Scadutree Blessing choices (grace submenu), from
# the vanilla regulation.bin, into src\param\SpEffectParam.scaling.rows.xml, and src\scaling.json (per boss:
# its rows). Rerun when bosses.json changes (the per-boss rows follow its order).
#
# NG+ in vanilla: a boss's NpcParam.GameClearSpEffectID (its NG+1 multipliers) is on from NG+1 on, times
# ClearCountCorrectParam[cycle] (row 1 = NG+1 = all 1 ... row 7 = NG+7). A reflection at NG+T in a world at
# NG+C gets: GameClear (C = 0, T >= 1) or its inverse (C >= 1, T = 0), the inverse of ClearCount[C] and
# ClearCount[T] (SpEffect rates multiply).
# Blessing in vanilla: the engine keeps SpEffect 20000100 + level on the player in DLC areas. The
# reflection adds the inverse of the current level's effect and the chosen level's.
param([string]$Game = 'D:\SteamLibrary\steamapps\common\ELDEN RING\Game',
      [string]$MsbDir = "$PSScriptRoot\..\work\msb")
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
$msbtool = "$PSScriptRoot\MsbDump\out\MsbDump.exe"
$defs = 'D:\mods\EldenRing\bin\WitchyBND\Assets\Paramdex\ER\Defs'
$reg = "$Game\regulation.bin"
$inv = [Globalization.CultureInfo]::InvariantCulture

function Get-Rows($param, $def, [int64[]]$ids) {
    Push-Location (Split-Path $msbtool)
    $out = & $msbtool reg-rows $reg $param "$defs\$def" (($ids | Select-Object -Unique) -join ',')
    Pop-Location
    $rows = @{}
    foreach ($l in $out) {
        if ($l -notmatch '^(\d+): (.*)$') { continue }
        $f = @{}; foreach ($kv in $matches[2] -split ' ') { $k, $v = $kv -split '=', 2; $f[$k] = $v }
        $rows[[int64]$matches[1]] = $f
    }
    $rows
}

# Multiplicative SpEffect fields (paramdef default 1): what an inverse row inverts.
$x = [xml](Get-Content "$defs\SpEffect.xml" -Raw)
$rateFields = @($x.PARAMDEF.Fields.Field | ? { $_.Def -match '^f32 (\w+) = 1$' } | % { ($_.Def -split ' ')[1] })

# ClearCountCorrectParam -> SpEffect fields (the ones that matter in a boss fight).
$cccMap = [ordered]@{
    MaxHpRate = 'maxHpRate'; MaxStaminaRate = 'maxStaminaRate'
    PhysicsAttackRate = 'physicsAttackPowerRate'; SlashAttackRate = 'slashAttackPowerRate'; BlowAttackRate = 'blowAttackPowerRate'
    ThrustAttackRate = 'thrustAttackPowerRate'; NeturalAttackRate = 'neutralAttackPowerRate'; MagicAttackRate = 'magicAttackPowerRate'
    FireAttackRate = 'fireAttackPowerRate'; ThunderAttackRate = 'thunderAttackPowerRate'; DarkAttackRate = 'darkAttackPowerRate'
    PhysicsDefenseRate = 'physicsDiffenceRate'; MagicDefenseRate = 'magicDiffenceRate'; FireDefenseRate = 'fireDiffenceRate'
    ThunderDefenseRate = 'thunderDiffenceRate'; DarkDefenseRate = 'darkDiffenceRate'; StaminaAttackRate = 'staminaAttackRate'
}
$targets = 'effectTargetSelf="1" effectTargetFriend="1" effectTargetEnemy="1" effectTargetPlayer="1" effectTargetAI="1" effectTargetLive="1" effectTargetGhost="1"'
function Num([double]$v) { $v.ToString('R', $inv) }

$xml = New-Object Collections.Generic.List[string]
$xml.Add('<!-- Generated by tools\gen_scaling.ps1: NG+ and Scadutree Blessing choices of the reflections (events 7980020/7980021). -->')
$xml.Add('<rows>')

# NG+ cycle factors: 7980200 + c cancels ClearCount[c], 7980210 + t applies ClearCount[t] (c, t = 2..7).
$ccc = Get-Rows ClearCountCorrectParam ClearCountCorrectParam.xml (1..7)
foreach ($n in 2..7) {
    $cancel = ($cccMap.Keys | % { "$($cccMap[$_])=`"$(Num (1 / [double]$ccc[[int64]$n][$_]))`"" }) -join ' '
    $apply = ($cccMap.Keys | % { "$($cccMap[$_])=`"$(Num ([double]$ccc[[int64]$n][$_]))`"" }) -join ' '
    $xml.Add("  <row id=`"$(7980200 + $n)`" copyFrom=`"20000100`" paramdexName=`"[Boss Reflections] NG+$n cycle factor, cancel`" spCategory=`"0`" effectEndurance=`"-1`" $cancel />")
    $xml.Add("  <row id=`"$(7980210 + $n)`" copyFrom=`"20000100`" paramdexName=`"[Boss Reflections] NG+$($n - 1) cycle factor`" spCategory=`"0`" effectEndurance=`"-1`" $apply />")
}

# Per boss: its GameClear effect (7980300 + i) and the inverse (7980350 + i), on the boss and its phase-one character.
$bosses = @((Get-Content "$root\src\bosses.json" -Raw -Encoding utf8 | ConvertFrom-Json).bosses)
$npcOf = @{}
foreach ($b in $bosses) {
    $l = Select-String "$MsbDir\*.txt" -Pattern "^$($b.bossEntity)\t.*npc=(\d+)" -Encoding utf8 | Select-Object -First 1
    if ($l) { $npcOf[$b.key] = [int64]$l.Matches[0].Groups[1].Value }
}
$npcs = Get-Rows NpcParam NpcParam.xml @($npcOf.Values)
$gIds = @{}; foreach ($k in $npcOf.Keys) { $g = [int64]$npcs[$npcOf[$k]].GameClearSpEffectID; if ($g -gt 0) { $gIds[$k] = $g } }
$gRows = Get-Rows SpEffectParam SpEffect.xml @($gIds.Values)
$scaling = [ordered]@{}
for ($i = 0; $i -lt $bosses.Count; $i++) {
    $b = $bosses[$i]; $g = $gIds[$b.key]
    if (-not $g -or -not $gRows[$g]) { Write-Host "$($b.key): no GameClear effect"; $scaling[$b.key] = [ordered]@{ g = 0; invG = 0 }; continue }
    $invFields = ($rateFields | ? { $gRows[$g][$_] -and [double]$gRows[$g][$_] -ne 1 -and [double]$gRows[$g][$_] -ne 0 } |
        % { "$_=`"$(Num (1 / [double]$gRows[$g][$_]))`"" }) -join ' '
    $xml.Add("  <row id=`"$(7980300 + $i)`" copyFrom=`"$g`" paramdexName=`"[Boss Reflections] $($b.key) NG+ (copy of $g)`" effectEndurance=`"-1`" $targets />")
    $xml.Add("  <row id=`"$(7980350 + $i)`" copyFrom=`"$g`" paramdexName=`"[Boss Reflections] $($b.key) NG+ inverse`" effectEndurance=`"-1`" $targets $invFields />")
    $scaling[$b.key] = [ordered]@{ g = 7980300 + $i; invG = 7980350 + $i }
    Write-Host ("{0,-20} npc {1} GameClear {2}: hp x{3}" -f $b.key, $npcOf[$b.key], $g, $gRows[$g].maxHpRate)
}

# Scadutree Blessing: 7980500 + L applies level L, 7980530 + L cancels it (L = 0..20).
$bl = Get-Rows SpEffectParam SpEffect.xml (0..20 | % { 20000100 + $_ })
foreach ($L in 0..20) {
    $src = 20000100 + $L
    $invFields = ($rateFields | ? { $bl[[int64]$src][$_] -and [double]$bl[[int64]$src][$_] -ne 1 -and [double]$bl[[int64]$src][$_] -ne 0 } |
        % { "$_=`"$(Num (1 / [double]$bl[[int64]$src][$_]))`"" }) -join ' '
    $xml.Add("  <row id=`"$(7980500 + $L)`" copyFrom=`"$src`" paramdexName=`"[Boss Reflections] Scadutree Blessing $L`" spCategory=`"0`" effectEndurance=`"-1`" stateInfo=`"0`" />")
    $xml.Add("  <row id=`"$(7980530 + $L)`" copyFrom=`"$src`" paramdexName=`"[Boss Reflections] Scadutree Blessing $L cancel`" spCategory=`"0`" effectEndurance=`"-1`" stateInfo=`"0`" $invFields />")
}
$xml.Add('</rows>')
[IO.File]::WriteAllLines("$root\src\param\SpEffectParam.scaling.rows.xml", $xml, (New-Object Text.UTF8Encoding $false))
[IO.File]::WriteAllText("$root\src\scaling.json", ([ordered]@{ comment = 'Generated by tools\gen_scaling.ps1'; bosses = $scaling } | ConvertTo-Json -Depth 4), (New-Object Text.UTF8Encoding $false))
"wrote $($xml.Count - 3) rows"
